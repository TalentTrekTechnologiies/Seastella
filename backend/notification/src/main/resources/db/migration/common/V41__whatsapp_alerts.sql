-- ============================================================================
--  notification: WhatsApp as a third alert channel
--
--  Asked for by the client in October 2026, beyond SoW s7 (in-app and email),
--  so a change request. Messages go through Meta's WhatsApp Cloud API on the
--  client's own Meta account; until its details are configured every WhatsApp
--  delivery is recorded as SKIPPED, exactly as email was before its mailbox.
-- ============================================================================

-- Which alerts also go to WhatsApp, per rule, next to in-app and email.
ALTER TABLE notification_rule ADD COLUMN whatsapp BOOLEAN NOT NULL DEFAULT FALSE;

-- The suggested starting set: only what needs someone to act now. A message
-- costs money and an alert people learn to ignore is worse than none, so
-- everything else stays in-app and email. The Platform Admin changes this.
UPDATE notification_rule SET whatsapp = TRUE
WHERE (event_type = 'RAISE'           AND recipient_role = 'SHIP_MANAGER')
   OR (event_type = 'RAISE_INVOICE'   AND recipient_role = 'SHIP_MANAGER')
   OR (event_type = 'ASSIGN_ENGINEER' AND recipient_role = 'SERVICE_ENGINEER')
   OR (event_type = 'COMPLETE'        AND recipient_role = 'SHIP_MANAGER')
   OR (event_type IN ('MAINTENANCE_DUE', 'EQUIPMENT_EXPIRING')
       AND recipient_role IN ('CAPTAIN', 'SHIP_MANAGER', 'TECHNICAL_HEAD'));

ALTER TABLE notification_delivery DROP CONSTRAINT ck_delivery_channel;
ALTER TABLE notification_delivery ADD CONSTRAINT ck_delivery_channel CHECK (channel IN ('EMAIL', 'WHATSAPP'));
CREATE INDEX ix_delivery_channel_status ON notification_delivery (channel, status, id);

-- One switch for all WhatsApp alerts, beside the email one.
ALTER TABLE notification_email_settings ADD COLUMN whatsapp_enabled BOOLEAN NOT NULL DEFAULT TRUE;

-- Meta sends only pre-approved templates. Every alert uses the platform's
-- default template unless the Platform Admin names another for its event -
-- for example once the client has had wording approved for invoices alone.
CREATE TABLE whatsapp_template (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type    VARCHAR(48)  NOT NULL,
    template_name VARCHAR(80)  NOT NULL,
    language_code VARCHAR(12)  NOT NULL,
    -- The template has an "Open" button whose link ends in a variable part.
    link_button   BOOLEAN      NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by    VARCHAR(160),
    updated_at    TIMESTAMP WITH TIME ZONE,
    updated_by    VARCHAR(160),
    version       BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT uk_whatsapp_template_event UNIQUE (event_type)
);
