-- ============================================================================
--  reporting: documents the platform issues for a vessel
--
--  The Shore Based Maintenance Certificate (SBMC) and the QM-F11 pre-survey
--  form, both rendered on the client's own templates (developer brief,
--  27 Oct 2026). Each issued file is also filed as one of the vessel's
--  documents, so it sits with the vessel's other certificates and the SBMC
--  expiry reaches the existing "certificate expiring" alert.
--
--  Nothing here is ever deleted. A new SBMC supersedes the last one; a wrong
--  one is revoked with a reason. The field snapshot keeps every value printed,
--  and the template version says which template it was printed on, so an old
--  certificate can be read exactly as it was issued.
-- ============================================================================

CREATE TABLE vessel_certificate (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vessel_id             BIGINT        NOT NULL,
    organization_id       BIGINT        NOT NULL,
    certificate_type      VARCHAR(16)   NOT NULL,
    certificate_number    VARCHAR(32)   NOT NULL,
    issue_date            DATE          NOT NULL,
    expiry_date           DATE          NOT NULL,
    status                VARCHAR(16)   NOT NULL,
    field_snapshot        VARCHAR(4000) NOT NULL,
    template_version      VARCHAR(32)   NOT NULL,
    document_id           BIGINT        NOT NULL,
    generated_by_user_id  BIGINT        NOT NULL,
    generated_by_role     VARCHAR(32)   NOT NULL,
    generated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    superseded_by_id      BIGINT,
    revoked_reason        VARCHAR(500),
    revoked_by_user_id    BIGINT,
    revoked_at            TIMESTAMP WITH TIME ZONE,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by            VARCHAR(160),
    updated_at            TIMESTAMP WITH TIME ZONE,
    updated_by            VARCHAR(160),
    version               BIGINT        NOT NULL DEFAULT 0,

    CONSTRAINT fk_vessel_certificate_vessel   FOREIGN KEY (vessel_id) REFERENCES vessel (id),
    CONSTRAINT fk_vessel_certificate_document FOREIGN KEY (document_id) REFERENCES document (id),
    CONSTRAINT fk_vessel_certificate_by       FOREIGN KEY (generated_by_user_id) REFERENCES app_user (id),
    CONSTRAINT uk_vessel_certificate_number   UNIQUE (certificate_number),
    CONSTRAINT ck_vessel_certificate_type     CHECK (certificate_type IN ('SBMC')),
    CONSTRAINT ck_vessel_certificate_status   CHECK (status IN ('ACTIVE', 'SUPERSEDED', 'REVOKED')),
    CONSTRAINT ck_vessel_certificate_dates    CHECK (expiry_date > issue_date),
    -- A revoked certificate always says why and who.
    CONSTRAINT ck_vessel_certificate_revoked  CHECK (
        status <> 'REVOKED' OR (revoked_reason IS NOT NULL AND revoked_by_user_id IS NOT NULL AND revoked_at IS NOT NULL))
);

CREATE INDEX ix_vessel_certificate_vessel ON vessel_certificate (vessel_id, id);

-- Certificate numbers run per year: TM-2026-0001, TM-2026-0002 ... Taken under
-- a row lock, so two certificates issued at the same moment never share one.
CREATE TABLE certificate_counter (
    counter_year  INTEGER NOT NULL PRIMARY KEY,
    last_number   INTEGER NOT NULL,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by    VARCHAR(160),
    updated_at    TIMESTAMP WITH TIME ZONE,
    updated_by    VARCHAR(160),
    version       BIGINT  NOT NULL DEFAULT 0
);

CREATE TABLE pre_survey_form (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vessel_id             BIGINT         NOT NULL,
    organization_id       BIGINT         NOT NULL,
    field_snapshot        VARCHAR(12000) NOT NULL,
    -- The values typed over the vessel's records for this form only.
    overrides             VARCHAR(6000),
    remarks               VARCHAR(2000),
    template_version      VARCHAR(32)    NOT NULL,
    document_id           BIGINT         NOT NULL,
    generated_by_user_id  BIGINT         NOT NULL,
    generated_by_role     VARCHAR(32)    NOT NULL,
    generated_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at            TIMESTAMP WITH TIME ZONE NOT NULL,
    created_by            VARCHAR(160),
    updated_at            TIMESTAMP WITH TIME ZONE,
    updated_by            VARCHAR(160),
    version               BIGINT         NOT NULL DEFAULT 0,

    CONSTRAINT fk_pre_survey_vessel   FOREIGN KEY (vessel_id) REFERENCES vessel (id),
    CONSTRAINT fk_pre_survey_document FOREIGN KEY (document_id) REFERENCES document (id),
    CONSTRAINT fk_pre_survey_by       FOREIGN KEY (generated_by_user_id) REFERENCES app_user (id)
);

CREATE INDEX ix_pre_survey_vessel ON pre_survey_form (vessel_id, id);
